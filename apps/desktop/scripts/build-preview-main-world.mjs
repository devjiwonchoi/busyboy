// Bundles src/preview/PreviewMainWorld.ts into one self-contained function for the preview
// preload to install in the page's world with `contextBridge.executeInMainWorld`. That API copies
// the function's source text, so the whole bundle must live inside the function body.
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import { build } from "vite-plus";

const directory = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const appRoot = NodePath.join(directory, "..");
const entryPath = NodePath.join(appRoot, "src", "preview", "PreviewMainWorld.ts");
const outputPath = NodePath.join(appRoot, "src", "preview", "PreviewMainWorld.generated.ts");

const result = await build({
  configFile: false,
  logLevel: "warn",
  root: appRoot,
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  build: {
    write: false,
    minify: true,
    target: "chrome130",
    lib: { entry: entryPath, formats: ["iife"], name: "BusyBoyPreviewMainWorld" },
  },
});

const outputs = (Array.isArray(result) ? result : [result]).flatMap((entry) => entry.output);
const chunk = outputs.find((output) => output.type === "chunk");
if (!chunk) throw new Error("PreviewMainWorld bundle produced no chunk.");

// The IIFE's `var BusyBoyPreviewMainWorld = ...` stays local to the wrapper function.
const moduleSource = `// Generated by scripts/build-preview-main-world.mjs. Do not edit.
// @ts-nocheck
/* oxlint-disable */
/* eslint-disable */
/** Installs the picker's page-world helper. Self-contained: see PreviewMainWorld.ts. */
export function installPreviewMainWorld(): void {
${chunk.code.trim()}
}
`;

await NodeFSP.writeFile(outputPath, moduleSource);
