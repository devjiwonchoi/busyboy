/**
 * Computer use needs the Cua driver that the macOS desktop app installs and
 * hands to its primary backend. Remote, standalone and non-macOS backends
 * have none.
 */
export class ComputerUseUnavailableError extends Schema.TaggedError<ComputerUseUnavailableError>()(
  "ComputerUseUnavailableError",
  {},
) {
  override get message(): string {
    return "Computer use is only available in the Busyboy desktop app on macOS.";
  }
}

export class ComputerUseDriverStartError extends Schema.TaggedError<ComputerUseDriverStartError>()(
  "ComputerUseDriverStartError",
  { cause: Schema.Defect() },
) {
  override get message(): string {
    return "The computer-use driver failed to start.";
  }
}

/** Where and how the driver runs. */
export interface ComputerUseWorkerSpec {
  /**
   * The generated launcher, which sets the driver's environment and execs
   * Busyboy Computer Use.app, which runs the driver under its own permissions.
   */
  readonly launcherPath: string;
  /** The app whose macOS permissions the driver uses. */
  readonly hostBundleId: string;
}

/** Busyboy Computer Use.app runs this instead of the driver. */
export const REQUEST_PERMISSIONS_ARGUMENT = "--request-permissions";

/** Starts one private driver worker. Tests replace this. */
export type ComputerUseWorkerFactory = (spec: ComputerUseWorkerSpec) => Promise<CuaDriverLike>;

export class ComputerUseDriver extends Context.Service<
  ComputerUseDriver,
  {
    readonly available: boolean;
    /** Runs `use` against the worker, starting it first if none is running. */
    readonly withWorker: <A, E, R>(
      use: (worker: CuaDriverLike) => Effect.Effect<A, E, R>,
    ) => Effect.Effect<A, E | ComputerUseUnavailableError | ComputerUseDriverStartError, R>;
    /** Stops the running worker; the next call starts a fresh one. */
    readonly restart: Effect.Effect<void>;
    /** Applies the keep-display-awake setting, restarting the worker if it changed. */
    readonly setKeepDisplayAwake: (enabled: boolean) => Effect.Effect<void>;
    /**
     * Has macOS ask the user to grant Busyboy Computer Use its permissions,
     * which also lists the app in System Settings. Agents' calls ask once per
     * run, so a missing permission does not prompt on every call.
     */
    readonly requestPermissions: (input: { readonly askedByUser: boolean }) => Effect.Effect<void>;
  }
>()("t3/computerUse/ComputerUseDriver") {}

// How long the driver keeps the display awake after its last tool call when
// the user turns the setting on. Matches Cua's own default.
const KEEP_DISPLAY_AWAKE_SECONDS = 600;

// Allowlisted variables the SDK passes to the worker. The launcher sets the
// same switches again, together with the ones the allowlist strips.
const WORKER_ENVIRONMENT = [
  ["CUA_TELEMETRY_ENABLED", "false"],
  ["CUA_DRIVER_RS_TELEMETRY_ENABLED", "false"],
  ["CUA_DRIVER_RS_UPDATE_CHECK", "false"],
] as const;

const shellQuote = (value: string) => `'${value.replaceAll("'", `'\\''`)}'`;

/**
 * The SDK clears the worker's environment and only passes allowlisted names,
 * which excludes Cua's display-awake switch. The launcher sets it, turns off
 * telemetry and update checks, keeps Cua's state under Busyboy's directory,
 * and then becomes the driver, so the driver stays in Busyboy's macOS
 * permission chain.
 */
export function computerUseLauncherScript(input: {
  readonly driverPath: string;
  readonly driverHome: string;
  readonly keepDisplayAwake: boolean;
}): string {
  return [
    "#!/bin/sh",
    "# Generated by Busyboy to start the Cua driver for computer use.",
    "export DO_NOT_TRACK=1",
    ...WORKER_ENVIRONMENT.map(([name, value]) => `export ${name}=${value}`),
    `export CUA_DRIVER_KEEP_DISPLAY_AWAKE=${input.keepDisplayAwake ? KEEP_DISPLAY_AWAKE_SECONDS : 0}`,
    `export CUA_DRIVER_RS_HOME=${shellQuote(input.driverHome)}`,
    `exec ${shellQuote(input.driverPath)} "$@"`,
    "",
  ].join("\n");
}

export const createPrivateWorker: ComputerUseWorkerFactory = async (spec) => {
  const sdk = await import("@trycua/cua-driver");
  return sdk.CuaDriver.createPrivateWorker(
    sdk.PrivateWorkerOptions.new({
      binaryPath: spec.launcherPath,
      hostBundleId: spec.hostBundleId,
      // A stop has to end an action that is still typing, so the worker gets
      // little time to finish before it is killed.
      shutdownTimeoutMs: 1_000n,
      configuredDriver: sdk.ConfiguredDriverOptions.new({
        claudeCodeCompatibility: false,
        authorization: sdk.RuntimeAuthorizationOptions.new({
          allowedModes: [sdk.SessionPermissionMode.Standard],
          compatibilityMode: sdk.SessionPermissionMode.Standard,
          unrestrictedAcknowledged: false,
          maxSessionTtlSeconds: 3_600n,
          maxIdleTtlSeconds: 600n,
        }),
      }),
      environment: WORKER_ENVIRONMENT.map(([name, value]) =>
        sdk.EmbeddedEnvironmentVariable.new({ name, value }),
      ),
      inheritStderr: false,
    }),
  );
};

const shutdownWorker = (worker: CuaDriverLike) =>
  Effect.tryPromise(() => worker.shutdown()).pipe(
    Effect.catchCause((cause) =>
      Effect.logWarning("Computer-use driver did not shut down cleanly", cause),
    ),
  );

export const make = Effect.fn("ComputerUseDriver.make")(function* (
  createWorker: ComputerUseWorkerFactory = createPrivateWorker,
) {
  const config = yield* ServerConfig.ServerConfig;
  const platform = yield* HostProcess.Platform;
  const fileSystem = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;

  const driverPath = config.computerUseDriverPath;
  if (platform !== "darwin" || driverPath === undefined) {
    const unavailable = new ComputerUseUnavailableError();
    return ComputerUseDriver.of({
      available: false,
      withWorker: () => Effect.fail(unavailable),
      restart: Effect.void,
      setKeepDisplayAwake: () => Effect.void,
      requestPermissions: () => Effect.void,
    });
  }

  const hostBundleId = config.computerUseHostBundleId ?? "dev.jiwon.busyboy.computer-use";
  const runner = yield* Effect.serviceOption(ProcessRunner.ProcessRunner);
  const directory = path.join(config.stateDir, "computer-use");
  const launcherPath = path.join(directory, "cua-driver-launcher");
  const driverHome = path.join(directory, "driver-home");

  const keepDisplayAwake = yield* Ref.make(false);
  const current = yield* Ref.make(Option.none<CuaDriverLike>());
  const lifecycle = yield* Semaphore.make(1);

  const writeLauncher = Effect.gen(function* () {
    yield* fileSystem.makeDirectory(directory, { recursive: true, mode: 0o700 });
    yield* fileSystem.makeDirectory(driverHome, { recursive: true, mode: 0o700 });
    const script = computerUseLauncherScript({
      driverPath,
      driverHome,
      keepDisplayAwake: yield* Ref.get(keepDisplayAwake),
    });
    const staged = `${launcherPath}.tmp`;
    yield* fileSystem.writeFileString(staged, script, { mode: 0o700 });
    yield* fileSystem.chmod(staged, 0o700);
    yield* fileSystem.rename(staged, launcherPath);
  });

  const stopWorker = Effect.gen(function* () {
    const worker = yield* Ref.getAndSet(current, Option.none());
    if (Option.isSome(worker)) yield* shutdownWorker(worker.value);
  });

  const acquire = lifecycle.withPermits(1)(
    Effect.gen(function* () {
      const running = yield* Ref.get(current);
      if (Option.isSome(running)) return running.value;
      yield* writeLauncher.pipe(
        Effect.mapError((cause) => new ComputerUseDriverStartError({ cause })),
      );
      const worker = yield* Effect.tryPromise({
        try: () => createWorker({ launcherPath, hostBundleId }),
        catch: (cause) => new ComputerUseDriverStartError({ cause }),
      });
      yield* Ref.set(current, Option.some(worker));
      return worker;
    }),
  );

  const restart = lifecycle.withPermits(1)(stopWorker);

  const permissionsRequested = yield* Ref.make(false);
  const requestPermissions = (input: { readonly askedByUser: boolean }) =>
    Effect.gen(function* () {
      const alreadyAsked = yield* Ref.getAndSet(permissionsRequested, true);
      if (Option.isNone(runner) || (alreadyAsked && !input.askedByUser)) return;
      yield* lifecycle.withPermits(1)(writeLauncher);
      yield* runner.value.run({
        command: launcherPath,
        args: [REQUEST_PERMISSIONS_ARGUMENT],
        timeout: "10 seconds",
      });
    }).pipe(
      Effect.catchCause((cause) =>
        Effect.logWarning("Could not ask macOS for the computer-use permissions", cause),
      ),
    );

  yield* Effect.addFinalizer(() => restart);

  return ComputerUseDriver.of({
    available: true,
    withWorker: (use) => Effect.flatMap(acquire, use),
    restart,
    setKeepDisplayAwake: (enabled) =>
      lifecycle.withPermits(1)(
        Effect.gen(function* () {
          if ((yield* Ref.getAndSet(keepDisplayAwake, enabled)) === enabled) return;
          // The launcher is rewritten when the next worker starts.
          yield* stopWorker;
        }),
      ),
    requestPermissions,
  });
});

export const layer = Layer.effect(ComputerUseDriver, make()).pipe(
  Layer.provide(ProcessRunner.layer),
);
